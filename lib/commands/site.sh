#!/usr/bin/env bash
set -euo pipefail

plume_site_prompt() {
  local label="$1"
  local var_name="$2"
  local fallback="${3:-}"

  if [[ -n "${fallback}" ]]; then
    printf -v "$var_name" '%s' "${fallback}"
    return 0
  fi

  if [[ ! -t 0 ]]; then
    return 1
  fi

  local input
  read -r -p "${label}: " input
  if [[ -z "${input}" ]]; then
    return 1
  fi

  printf -v "$var_name" '%s' "${input}"
}

plume_site_usage() {
  cat <<'EOF'
plumectl site <subcommand>

subcommands:
  add      Add a project and register it in Plume registry
  update   Update registered site settings (non-destructive by default)
  publish  Rebuild and write local web-server snippet
  list     List all registered sites
  modes    List registered sites with mode visibility
  check    Show site detail (id required)
  remove   Remove a registered site (id required)

Add options:
  --path=</abs/project/path>      Required for add
  --domain=<example.test,...>     Comma-separated domains
  --server=nginx|apache2|caddy    Default: nginx
  --php=<8.1|8.2|8.3|8.4|default> PHP runtime for this site (default: global default)
  --php-upstream=<host:port|unix:/sock> Optional upstream override for this site
  --mode=native|docker-lite|laradock-bridge Default: current mode
  --port=80                        HTTP listener port
  --https-port=443                 HTTPS listener port (when cert is set)
  --cert-id=<cert-id>              Bind local cert generated by 'security cert issue'
  --clear-cert                     Remove cert binding (update only; HTTP-only snippet)
  --document-root=public
  --horizon                       Enable native Horizon worker for this site (supervisor program)
  --no-horizon                    Disable Horizon for this site (update only)
  --server-config=/abs/conf       Path to custom web-server config/snippet (optional)
  --publish                       Write local web-server snippet (add/update)
  --reload                        Reload web server after publish (nginx/apache2/caddy)
  --dry-run                       Validate and print planned action without changes
  --force                         Ignore domain/path conflicts

Examples:
  plumectl site add --path=/var/www/myapp --domain=myapp.test --server=nginx --publish --server-config=/tmp/myapp.nginx.conf
  plumectl site list
  plumectl site check site-171xxxx
  plumectl site update site-171xxxx --domain=myapp.test,www.myapp.test --publish
  plumectl site update site-171xxxx --clear-cert --publish --reload
  plumectl site publish site-171xxxx --reload
  plumectl site remove site-171xxxx
EOF
}

plume_site_parse_args() {
  PLUME_SITE_PATH=""
  PLUME_SITE_DOMAIN=""
  PLUME_SITE_SERVER="nginx"
  PLUME_SITE_MODE=""
  PLUME_SITE_PHP_VERSION=""
  PLUME_SITE_PHP_UPSTREAM=""
  PLUME_SITE_PORT="80"
  PLUME_SITE_HTTPS_PORT="${PLUME_WEB_HTTPS_PORT:-443}"
  PLUME_SITE_DOCUMENT_ROOT="public"
  PLUME_SITE_PUBLISH="false"
  PLUME_SITE_FORCE="false"
  PLUME_SITE_SERVER_CONFIG=""
  PLUME_SITE_RELOAD="false"
  PLUME_SITE_DRY_RUN="false"
  PLUME_SITE_PATH_SET="false"
  PLUME_SITE_DOMAIN_SET="false"
  PLUME_SITE_PORT_SET="false"
  PLUME_SITE_HTTPS_PORT_SET="false"
  PLUME_SITE_PHP_VERSION_SET="false"
  PLUME_SITE_PHP_UPSTREAM_SET="false"
  PLUME_SITE_SERVER_SET="false"
  PLUME_SITE_DOCUMENT_ROOT_SET="false"
  PLUME_SITE_SERVER_CONFIG_SET="false"
  PLUME_SITE_CERT_ID=""
  PLUME_SITE_CERT_ID_SET="false"
  PLUME_SITE_CLEAR_CERT="false"
  PLUME_SITE_HORIZON=""
  PLUME_SITE_HORIZON_SET="false"

  local arg
  for arg in "$@"; do
    case "${arg}" in
      --path=*) PLUME_SITE_PATH="${arg#*=}"; PLUME_SITE_PATH_SET="true" ;;
      --domain=*) PLUME_SITE_DOMAIN="${arg#*=}"; PLUME_SITE_DOMAIN_SET="true" ;;
      --server=*) PLUME_SITE_SERVER="${arg#*=}"; PLUME_SITE_SERVER_SET="true" ;;
      --php=*) PLUME_SITE_PHP_VERSION="${arg#*=}"; PLUME_SITE_PHP_VERSION_SET="true" ;;
      --php-version=*) PLUME_SITE_PHP_VERSION="${arg#*=}"; PLUME_SITE_PHP_VERSION_SET="true" ;;
      --php-upstream=*) PLUME_SITE_PHP_UPSTREAM="${arg#*=}"; PLUME_SITE_PHP_UPSTREAM_SET="true" ;;
      --mode=*) PLUME_SITE_MODE="${arg#*=}" ;;
      --port=*) PLUME_SITE_PORT="${arg#*=}"; PLUME_SITE_PORT_SET="true" ;;
      --https-port=*) PLUME_SITE_HTTPS_PORT="${arg#*=}"; PLUME_SITE_HTTPS_PORT_SET="true" ;;
      --document-root=*) PLUME_SITE_DOCUMENT_ROOT="${arg#*=}"; PLUME_SITE_DOCUMENT_ROOT_SET="true" ;;
      --server-config=*) PLUME_SITE_SERVER_CONFIG="${arg#*=}"; PLUME_SITE_SERVER_CONFIG_SET="true" ;;
      --cert-id=*) PLUME_SITE_CERT_ID="${arg#*=}"; PLUME_SITE_CERT_ID_SET="true" ;;
      --clear-cert) PLUME_SITE_CLEAR_CERT="true" ;;
      --horizon) PLUME_SITE_HORIZON="true"; PLUME_SITE_HORIZON_SET="true" ;;
      --no-horizon) PLUME_SITE_HORIZON="false"; PLUME_SITE_HORIZON_SET="true" ;;
      --tls=false) PLUME_SITE_CLEAR_CERT="true" ;;
      --nginx-config=*)
        plume_warn "--nginx-config is deprecated; use --server-config"
        PLUME_SITE_SERVER_CONFIG="${arg#*=}"
        PLUME_SITE_SERVER_CONFIG_SET="true"
        ;;
      --publish) PLUME_SITE_PUBLISH="true" ;;
      --force) PLUME_SITE_FORCE="true" ;;
      --reload) PLUME_SITE_RELOAD="true" ;;
      --dry-run) PLUME_SITE_DRY_RUN="true" ;;
      *)
        plume_err "unknown site option: ${arg}"
        return 2
        ;;
    esac
  done
}

plume_site_mode_override_from_args() {
  local mode=""
  local expect_next="false"
  local arg
  for arg in "$@"; do
    if [[ "${expect_next}" == "true" ]]; then
      mode="${arg}"
      expect_next="false"
      continue
    fi
    case "${arg}" in
      --mode=*) mode="${arg#*=}" ;;
      --mode) expect_next="true" ;;
    esac
  done

  if [[ "${expect_next}" == "true" ]]; then
    plume_err "missing value for --mode"
    return 2
  fi

  printf '%s' "${mode}"
}

plume_site_php_installed_versions_csv() {
  local default_v installed merged item
  default_v="${PLUME_PHP_DEFAULT_VERSION:-${PLUME_PHP_VERSION:-8.3}}"
  installed="${PLUME_PHP_INSTALLED_VERSIONS:-8.1,8.2,8.3}"
  merged="${installed},${default_v}"
  local out=""
  local first="true"
  local -a items=()
  IFS=',' read -r -a items <<< "${merged}"
  for item in "${items[@]}"; do
    item="$(printf '%s' "${item}" | tr -d ' ')"
    [[ -z "${item}" ]] && continue
    if [[ ",${out}," == *",${item},"* ]]; then
      continue
    fi
    if [[ "${first}" == "true" ]]; then
      out="${item}"
      first="false"
    else
      out="${out},${item}"
    fi
  done
  printf '%s' "${out}"
}

plume_site_resolve_php_version() {
  local requested="${1:-}"
  local normalized
  if ! normalized="$(plume_sites_php_version_normalize "${requested:-default}")"; then
    plume_err "invalid php version: ${requested}"
    return 2
  fi

  local installed_csv
  installed_csv="$(plume_site_php_installed_versions_csv)"
  if [[ ",${installed_csv}," != *",${normalized},"* ]]; then
    plume_err "php version is not installed/enabled for plume: ${normalized} (installed: ${installed_csv})"
    return 2
  fi

  printf '%s' "${normalized}"
}

plume_site_php_version_from_manifest() {
  local project_root="$1"
  local hint=""
  if ! hint="$(plume_yml_project_php_version "${project_root}")"; then
    return 1
  fi
  printf '%s' "${hint}"
}

plume_site_resolve_mode() {
  local explicit="$1"
  local project_root="${2:-}"
  local hint="${3:-}"
  local mode=""

  if [[ -n "${explicit}" ]]; then
    mode="${explicit}"
  elif [[ -n "${project_root}" ]]; then
    if mode="$(plume_yml_project_mode "${project_root}")"; then
      :
    fi
  fi

  if [[ -z "${mode}" && -n "${hint}" ]]; then
    mode="${hint}"
  fi

  if [[ -z "${mode}" ]]; then
    mode="$(plume_mode_current)"
  fi

  printf '%s' "${mode}"
}

plume_site_record_mode() {
  local site_id="$1"
  if ! plume_sites_exists "${site_id}"; then
    return 1
  fi

  local record_file
  record_file="$(plume_sites_file "${site_id}")"
  local record_mode
  record_mode="$(plume_sites_record_value "${record_file}" mode)"

  if [[ -z "${record_mode}" ]]; then
    return 1
  fi

  printf '%s' "${record_mode}"
}

plume_site_validate_mode() {
  local mode="$1"
  case "${mode}" in
    native|docker-lite|laradock-bridge) return 0 ;;
    *) return 1 ;;
  esac
}

plume_site_expand_tilde() {
  local value="$1"
  printf '%s' "${value/#\~/$HOME}"
}

plume_site_to_abs_path() {
  local value="$1"

  if [[ -z "${value}" ]]; then
    printf '%s' ""
    return 0
  fi

  value="$(plume_site_expand_tilde "${value}")"
  if [[ "${value}" = /* ]]; then
    printf '%s' "${value}"
    return 0
  fi

  local parent
  local base
  parent="$(dirname "${value}")"
  base="$(basename "${value}")"
  if parent="$(cd "${parent}" 2>/dev/null && pwd)"; then
    printf '%s/%s' "${parent}" "${base}"
    return 0
  fi

  return 1
}

plume_site_join_domains() {
  local -a items=("$@")
  local first="true"
  local out=""
  local d
  for d in "${items[@]}"; do
    [[ -z "${d}" ]] && continue
    if [[ "${first}" == "true" ]]; then
      out="${d}"
      first="false"
    else
      out="${out},${d}"
    fi
  done
  printf '%s' "${out}"
}

plume_site_plan_print() {
  local action="$1"
  local site_id="${2:-}"
  local mode="${3:-}"
  local path="${4:-}"
  local server="${5:-}"
  local port="${6:-}"
  local domains="${7:-}"
  local php_version="${8:-}"
  local cert_id="${9:-}"
  local https_port="${10:-}"

  if [[ "${PLUME_OUTPUT:-text}" == "json" ]]; then
    printf '{"ok":true,"command":"site %s","data":{"dry_run":true,"id":"%s","mode":"%s","path":"%s","server":"%s","php_version":"%s","port":"%s","domains":"%s"},"warnings":[],"errors":[]}\n' \
      "${action}" "${site_id}" "${mode}" "${path}" "${server}" "${php_version}" "${port}" "${domains}"
    return 0
  fi

  printf '%s\n' "[DRY-RUN] action=${action} id=${site_id} mode=${mode} server=${server} php=${php_version} port=${port} https_port=${https_port} cert_id=${cert_id} path=${path} domains=${domains}"
}

plume_site_parse_domains() {
  local raw="$1"
  local item
  local normalized
  local -a list=()
  local domain
  IFS=',' read -r -a list <<< "${raw}"
  for domain in "${list[@]}"; do
    normalized="$(printf '%s' "${domain}" | sed 's/^ *//;s/ *$//')"
    [[ -n "${normalized}" ]] && printf '%s\n' "${normalized}"
  done
}

plume_site_validate_port() {
  local value="$1"
  [[ -n "${value}" ]] || return 1
  if ! printf '%s\n' "${value}" | grep -Eq '^[0-9]+$'; then
    return 1
  fi
  if (( value < 1 || value > 65535 )); then
    return 1
  fi
  return 0
}

plume_site_validate_php_upstream() {
  local value="${1:-}"
  [[ -n "${value}" ]] || return 0
  if [[ "${value}" =~ ^unix:/.+$ ]]; then
    return 0
  fi
  if [[ "${value}" =~ ^[A-Za-z0-9._-]+:[0-9]+$ ]]; then
    return 0
  fi
  return 1
}

plume_site_resolve_server_config() {
  local server="$1"
  local configured="${2:-}"

  if [[ -z "${configured}" ]]; then
    printf '%s' ""
    return 0
  fi

  configured="$(plume_site_to_abs_path "${configured}")" || {
    plume_err "invalid server config path: ${2:-}"
    return 2
  }

  if [[ ! -f "${configured}" ]]; then
    plume_err "custom server config not found: ${configured}"
    return 2
  fi

  printf '%s' "${configured}"
}

cmd_site_add() {
  local path domain server php_version php_upstream port https_port cert_id document_root publish force server_config server_config_set dry_run
  local mode_override=""
  mode_override="$(plume_site_mode_override_from_args "$@")" || return 2
  plume_site_parse_args "$@" || return 2

  if [[ "${PLUME_SITE_CLEAR_CERT}" == "true" ]]; then
    plume_err "--clear-cert is only supported for site update"
    return 2
  fi

  local resolved_mode
  path="${PLUME_SITE_PATH}"
  domain="${PLUME_SITE_DOMAIN}"
  server="${PLUME_SITE_SERVER}"
  php_version="${PLUME_SITE_PHP_VERSION:-default}"
  php_upstream="${PLUME_SITE_PHP_UPSTREAM}"
  port="${PLUME_SITE_PORT}"
  https_port="${PLUME_SITE_HTTPS_PORT}"
  cert_id="${PLUME_SITE_CERT_ID}"
  document_root="${PLUME_SITE_DOCUMENT_ROOT}"
  publish="${PLUME_SITE_PUBLISH}"
  force="${PLUME_SITE_FORCE}"
  dry_run="${PLUME_SITE_DRY_RUN}"
  server_config="${PLUME_SITE_SERVER_CONFIG}"
  server_config_set="${PLUME_SITE_SERVER_CONFIG_SET}"

  if [[ -z "${path}" ]]; then
    if ! plume_site_prompt "Project path" path; then
      plume_err "project path is required"
      return 2
    fi
  fi

  if [[ -z "${domain}" ]]; then
    if ! plume_site_prompt "Domains (comma separated)" domain; then
      plume_err "at least one domain is required"
      return 2
    fi
  fi

  if [[ -z "${path}" || -z "${domain}" ]]; then
    plume_err "path and domain are required"
    return 2
  fi

  if ! plume_site_validate_port "${port}"; then
    plume_err "invalid port: ${port}"
    return 2
  fi
  if ! plume_site_validate_port "${https_port}"; then
    plume_err "invalid https port: ${https_port}"
    return 2
  fi

  if [[ ! -d "${path}" ]]; then
    plume_err "invalid path: ${path}"
    return 2
  fi

  path="$(cd "${path}" && pwd)"

  if [[ "${PLUME_SITE_PHP_VERSION_SET}" != "true" ]]; then
    local manifest_php=""
    if manifest_php="$(plume_site_php_version_from_manifest "${path}")"; then
      php_version="${manifest_php}"
    fi
  fi

  resolved_mode="$(plume_site_resolve_mode "${PLUME_SITE_MODE}" "${path}" "${PLUME_MODE_HINT:-}")"
  if ! plume_site_validate_mode "${resolved_mode}"; then
    plume_err "invalid mode: ${resolved_mode}"
    return 2
  fi

  if [[ "${dry_run}" != "true" ]]; then
    plume_macos_permissions_maybe_prompt_site_path "site-add" "${path}" "${resolved_mode}" || return 2
  fi

  local domains=()
  local domain_item
  while IFS= read -r domain_item; do
    [[ -n "${domain_item}" ]] && domains+=("${domain_item}")
  done < <(plume_site_parse_domains "${domain}")

  if [[ ${#domains[@]} -eq 0 ]]; then
    plume_err "at least one domain is required"
    return 2
  fi

  if [[ "${server}" != "nginx" && "${server}" != "apache2" && "${server}" != "caddy" ]]; then
    plume_err "unsupported server: ${server}"
    return 2
  fi

  php_version="$(plume_site_resolve_php_version "${php_version}")" || return 2
  if ! plume_site_validate_php_upstream "${php_upstream}"; then
    plume_err "invalid php upstream format: ${php_upstream} (expected host:port or unix:/path.sock)"
    return 2
  fi

  if [[ "${server_config_set}" == "true" ]]; then
    server_config="$(plume_site_resolve_server_config "${server}" "${PLUME_SITE_SERVER_CONFIG}")" || return 2
  else
    server_config=""
  fi

  if [[ -n "${cert_id}" ]]; then
    if ! plume_sites_cert_exists "${cert_id}"; then
      plume_err "certificate not found for cert_id=${cert_id}; issue via: plume.sh security cert issue --domains=..."
      return 2
    fi
  fi

  if [[ "${force}" != "true" ]]; then
    for domain_item in "${domains[@]}"; do
      if plume_site_conflict_domain "${domain_item}"; then
        plume_err "domain conflict: ${domain_item}"
        return 2
      fi
    done

    if plume_site_conflict_path "${path}"; then
      plume_err "path conflict: ${path}"
      return 2
    fi

    if plume_site_conflict_port "${port}"; then
      plume_err "port conflict: ${port}"
      return 2
    fi
  fi

  local site_id
  site_id="$(plume_sites_id "")"
  local horizon_flag=""
  if [[ "${PLUME_SITE_HORIZON_SET}" == "true" ]]; then
    horizon_flag="${PLUME_SITE_HORIZON}"
  fi

  if [[ "${dry_run}" == "true" ]]; then
    plume_site_plan_print "add" "${site_id}" "${resolved_mode}" "${path}" "${server}" "${port}" "$(plume_site_join_domains "${domains[@]}")" "${php_version}" "${cert_id}" "${https_port}"
    return 0
  fi

  if ! plume_sites_write_record "${site_id}" "${resolved_mode}" "${path}" "${server}" "${document_root}" "${port}" "active" "${php_version}" "${server_config}" "${cert_id}" "${https_port}" "${php_upstream}" "${horizon_flag}" "${domains[@]}"; then
    return 2
  fi

  if ! plume_sites_index_upsert "${site_id}"; then
    rm -f "$(plume_sites_file "${site_id}")"
    return 2
  fi

  if [[ "${publish}" == "true" ]]; then
    if ! plume_sites_publish_nginx "${site_id}" "${resolved_mode}"; then
      rm -f "$(plume_sites_file "${site_id}")"
      plume_sites_index_remove "${site_id}"
      plume_err "publish failed"
      return 2
    fi
  fi

  if [[ "${PLUME_OUTPUT:-text}" == "json" ]]; then
    local add_warnings="" add_tcc_hint=""
    if plume_sites_path_is_macos_tcc_sensitive "${path}" && declare -F plume_macos_permissions_site_tcc_hint >/dev/null 2>&1; then
      add_tcc_hint="$(plume_macos_permissions_site_tcc_hint "${path}")"
      add_warnings="\"$(printf '%s' "${add_tcc_hint}" | sed 's/\\/\\\\/g; s/"/\\"/g')\""
    fi
    printf '{"ok":true,"command":"site add","data":{"id":"%s","path":"%s","server":"%s","php_version":"%s","https_port":"%s","cert_id":"%s","domains":[' \
      "${site_id}" "${path}" "${server}" "${php_version}" "${https_port}" "${cert_id}"
    local first="true"
    for domain_item in "${domains[@]}"; do
      if [[ "${first}" == "true" ]]; then
        first="false"
      else
        printf ','
      fi
      printf '"%s"' "${domain_item}"
    done
    if [[ -n "${add_warnings}" ]]; then
      printf ']},"warnings":[%s],"errors":[]}\n' "${add_warnings}"
    else
      printf ']},"warnings":[],"errors":[]}\n'
    fi
  else
    printf '%s\n' "${site_id}"
    plume_macos_permissions_warn_site_path "${path}" "${resolved_mode}" || true
  fi
}

cmd_site_update() {
  local site_id="${1:-}"
  shift || true
  local resolved_mode
  local original_mode

  if [[ -z "${site_id}" ]]; then
    plume_err "site id required"
    return 2
  fi

  if ! plume_sites_exists "${site_id}"; then
    plume_err "site not found: ${site_id}"
    return 2
  fi

  plume_site_parse_args "$@" || return 2

  local file
  file="$(plume_sites_file "${site_id}")"
  original_mode="$(plume_site_record_mode "${site_id}" || true)"

  local current_path current_server current_port current_https_port current_cert_id current_document_root current_server_config current_php_version current_php_upstream current_horizon
  current_path="$(plume_sites_record_value "${file}" path)"
  current_server="$(plume_sites_record_value "${file}" server)"
  current_port="$(plume_sites_record_port "${file}")"
  current_https_port="$(plume_sites_record_https_port "${file}")"
  current_cert_id="$(plume_sites_record_cert_id "${file}")"
  current_document_root="$(plume_sites_record_value "${file}" document_root)"
  current_server_config="$(plume_sites_record_server_config "${file}")"
  current_php_version="$(plume_sites_record_php_version "${file}")"
  current_php_upstream="$(plume_sites_record_php_upstream "${file}")"
  current_horizon="$(plume_sites_record_horizon_enabled "${file}")"
  [[ -n "${current_document_root}" ]] || current_document_root="public"

  local path="${current_path}"
  local server="${current_server}"
  local php_version="${current_php_version}"
  local php_upstream="${current_php_upstream}"
  local horizon="${current_horizon}"
  local port="${current_port}"
  local https_port="${current_https_port}"
  local cert_id="${current_cert_id}"
  local document_root="${current_document_root}"
  local server_config="${current_server_config}"
  local publish="${PLUME_SITE_PUBLISH}"
  local force="${PLUME_SITE_FORCE}"
  local dry_run="${PLUME_SITE_DRY_RUN}"

  resolved_mode="$(plume_site_record_mode "${site_id}")"
  if [[ -n "${PLUME_MODE:-}" ]]; then
    resolved_mode="${PLUME_MODE}"
  elif [[ -n "${PLUME_SITE_MODE:-}" ]]; then
    resolved_mode="${PLUME_SITE_MODE}"
  elif [[ -z "${resolved_mode}" ]]; then
    resolved_mode="$(plume_site_resolve_mode "${PLUME_SITE_MODE:-}" "" "${PLUME_MODE_HINT:-}")"
  fi

  if ! plume_site_validate_mode "${resolved_mode}"; then
    plume_err "invalid mode: ${resolved_mode}"
    return 2
  fi

  local domains=()
  local domain_item
  if [[ "${PLUME_SITE_PATH_SET}" == "true" ]]; then
    if [[ -z "${PLUME_SITE_PATH}" ]]; then
      plume_err "project path is required"
      return 2
    fi

    path="${PLUME_SITE_PATH}"
    if [[ ! -d "${path}" ]]; then
      plume_err "invalid path: ${path}"
      return 2
    fi
    path="$(cd "${path}" && pwd)"
  fi

  if [[ "${PLUME_SITE_SERVER_SET}" == "true" ]]; then
    server="${PLUME_SITE_SERVER}"
  fi

  if [[ "${PLUME_SITE_PHP_VERSION_SET}" == "true" ]]; then
    php_version="${PLUME_SITE_PHP_VERSION}"
  fi
  if [[ "${PLUME_SITE_PHP_UPSTREAM_SET}" == "true" ]]; then
    php_upstream="${PLUME_SITE_PHP_UPSTREAM}"
  fi
  if [[ "${PLUME_SITE_HORIZON_SET}" == "true" ]]; then
    horizon="${PLUME_SITE_HORIZON}"
  elif [[ -z "$(plume_sites_record_value "${file}" horizon 2>/dev/null || true)" ]]; then
    horizon=""
  fi

  if [[ "${PLUME_SITE_PORT_SET}" == "true" ]]; then
    port="${PLUME_SITE_PORT}"
  fi
  if [[ "${PLUME_SITE_HTTPS_PORT_SET}" == "true" ]]; then
    https_port="${PLUME_SITE_HTTPS_PORT}"
  fi

  if ! plume_site_validate_port "${port}"; then
    plume_err "invalid port: ${port}"
    return 2
  fi
  if ! plume_site_validate_port "${https_port}"; then
    plume_err "invalid https port: ${https_port}"
    return 2
  fi

  if [[ "${PLUME_SITE_DOCUMENT_ROOT_SET}" == "true" ]]; then
    document_root="${PLUME_SITE_DOCUMENT_ROOT}"
  fi

  if [[ "${PLUME_SITE_DOMAIN_SET}" == "true" ]]; then
    while IFS= read -r domain_item; do
      [[ -n "${domain_item}" ]] && domains+=("${domain_item}")
    done < <(plume_site_parse_domains "${PLUME_SITE_DOMAIN}")
    if [[ ${#domains[@]} -eq 0 ]]; then
      plume_err "at least one domain is required"
      return 2
    fi
  else
    while IFS= read -r domain_item; do
      domains+=("${domain_item}")
    done < <(plume_sites_record_domains "${file}")
  fi

  if [[ "${PLUME_SITE_SERVER_CONFIG_SET}" == "true" ]]; then
    server_config="$(plume_site_resolve_server_config "${server}" "${PLUME_SITE_SERVER_CONFIG}")" || return 2
  fi
  if [[ "${PLUME_SITE_CLEAR_CERT}" == "true" && "${PLUME_SITE_CERT_ID_SET}" == "true" && -n "${PLUME_SITE_CERT_ID}" ]]; then
    plume_err "use either --clear-cert or --cert-id, not both"
    return 2
  fi
  if [[ "${PLUME_SITE_CLEAR_CERT}" == "true" ]]; then
    cert_id=""
  elif [[ "${PLUME_SITE_CERT_ID_SET}" == "true" ]]; then
    cert_id="${PLUME_SITE_CERT_ID}"
  fi

  if [[ "${server}" != "nginx" && "${server}" != "apache2" && "${server}" != "caddy" ]]; then
    plume_err "unsupported server: ${server}"
    return 2
  fi
  if [[ -n "${cert_id}" ]]; then
    if ! plume_sites_cert_exists "${cert_id}"; then
      plume_err "certificate not found for cert_id=${cert_id}; issue via: plume.sh security cert issue --domains=..."
      return 2
    fi
  fi
  php_version="$(plume_site_resolve_php_version "${php_version}")" || return 2
  if ! plume_site_validate_php_upstream "${php_upstream}"; then
    plume_err "invalid php upstream format: ${php_upstream} (expected host:port or unix:/path.sock)"
    return 2
  fi

  if [[ "${force}" != "true" ]]; then
    if [[ "${PLUME_SITE_DOMAIN_SET}" == "true" ]]; then
      local existing_domain
      for domain_item in "${domains[@]}"; do
        if plume_site_conflict_domain "${domain_item}" "${site_id}"; then
          plume_err "domain conflict: ${domain_item}"
          return 2
        fi
      done
    fi

    if [[ "${PLUME_SITE_PATH_SET}" == "true" ]] && [[ "${path}" != "${current_path}" ]]; then
      if plume_site_conflict_path "${path}" "${site_id}"; then
        plume_err "path conflict: ${path}"
        return 2
      fi
    fi

    if [[ "${PLUME_SITE_PORT_SET}" == "true" ]] && [[ "${port}" != "${current_port}" ]]; then
      if plume_site_conflict_port "${port}" "${site_id}"; then
        plume_err "port conflict: ${port}"
        return 2
      fi
    fi
  fi

  if [[ "${dry_run}" != "true" ]] && [[ "${PLUME_SITE_PATH_SET}" == "true" ]] && [[ "${path}" != "${current_path}" ]]; then
    plume_macos_permissions_maybe_prompt_site_path "site-update" "${path}" "${resolved_mode}" || return 2
  fi

  if [[ "${dry_run}" == "true" ]]; then
    plume_site_plan_print "update" "${site_id}" "${resolved_mode}" "${path}" "${server}" "${port}" "$(plume_site_join_domains "${domains[@]}")" "${php_version}" "${cert_id}" "${https_port}"
    return 0
  fi

  local rollback_record
  rollback_record="$(mktemp)"
  cp -f "${file}" "${rollback_record}"

  if ! plume_sites_write_record "${site_id}" "${resolved_mode}" "${path}" "${server}" "${document_root}" "${port}" "active" "${php_version}" "${server_config}" "${cert_id}" "${https_port}" "${php_upstream}" "${horizon}" "${domains[@]}"; then
    rm -f "${rollback_record}"
    return 2
  fi

  if ! plume_site_validate_mode "${resolved_mode}"; then
    plume_err "invalid mode: ${resolved_mode}"
    cp -f "${rollback_record}" "${file}" >/dev/null 2>&1 || true
    rm -f "${rollback_record}"
    return 2
  fi

  if [[ "${publish}" == "true" ]]; then
    if ! plume_sites_publish_nginx "${site_id}" "${resolved_mode}"; then
      cp -f "${rollback_record}" "${file}" >/dev/null 2>&1 || true
      plume_sites_publish_nginx "${site_id}" "${resolved_mode}" >/dev/null 2>&1 || true
      rm -f "${rollback_record}"
      plume_err "publish failed"
      return 2
    fi
  fi

  if [[ -n "${original_mode}" && "${original_mode}" != "${resolved_mode}" ]]; then
    plume_sites_cleanup_mode_artifacts "${site_id}" "${original_mode}"
  fi
  rm -f "${rollback_record}"

  if [[ "${PLUME_OUTPUT:-text}" == "json" ]]; then
    local update_warnings="" update_tcc_hint=""
    if plume_sites_path_is_macos_tcc_sensitive "${path}" && declare -F plume_macos_permissions_site_tcc_hint >/dev/null 2>&1; then
      update_tcc_hint="$(plume_macos_permissions_site_tcc_hint "${path}")"
      update_warnings="\"$(printf '%s' "${update_tcc_hint}" | sed 's/\\/\\\\/g; s/"/\\"/g')\""
    fi
    printf '{"ok":true,"command":"site update","data":{"id":"%s","path":"%s","server":"%s","php_version":"%s","https_port":"%s","cert_id":"%s","domains":[' \
      "${site_id}" "${path}" "${server}" "${php_version}" "${https_port}" "${cert_id}"
    local first="true"
    for domain_item in "${domains[@]}"; do
      if [[ "${first}" == "true" ]]; then
        first="false"
      else
        printf ','
      fi
      printf '"%s"' "${domain_item}"
    done
    if [[ -n "${update_warnings}" ]]; then
      printf ']},"warnings":[%s],"errors":[]}\n' "${update_warnings}"
    else
      printf ']},"warnings":[],"errors":[]}\n'
    fi
  else
    printf '%s\n' "${site_id}"
    plume_macos_permissions_warn_site_path "${path}" "${resolved_mode}" || true
  fi
}

cmd_site_modes() {
  if [[ "${PLUME_OUTPUT:-text}" == "json" ]]; then
    printf '{"ok":true,"command":"site modes","data":{"sites":['
    local first="true"
    while IFS= read -r site_id; do
      [[ -z "${site_id}" ]] && continue
      local file path mode server php_version status
      file="$(plume_sites_file "${site_id}")"
      path="$(plume_sites_record_value "${file}" path)"
      mode="$(plume_site_record_mode "${site_id}" || true)"
      server="$(plume_sites_record_value "${file}" server)"
      php_version="$(plume_sites_record_php_version "${file}")"
      status="$(plume_sites_record_value "${file}" status)"
      if [[ "${first}" == "true" ]]; then
        first="false"
      else
        printf ','
      fi
      printf '{"id":"%s","mode":"%s","server":"%s","php_version":"%s","status":"%s","path":"%s"}' \
        "${site_id}" "${mode}" "${server}" "${php_version}" "${status}" "${path}"
    done < <(plume_sites_index_ids)
    printf '],"warnings":[],"errors":[]}\n'
    return 0
  fi

  local -a rows=()
  local header_id="ID"
  local header_mode="MODE"
  local header_server="SERVER"
  local header_php="PHP"
  local header_status="STATUS"
  local header_path="PATH"
  local width_id="${#header_id}"
  local width_mode="${#header_mode}"
  local width_server="${#header_server}"
  local width_php="${#header_php}"
  local width_status="${#header_status}"
  local width_path="${#header_path}"

  while IFS= read -r site_id; do
    [[ -z "${site_id}" ]] && continue
    local file path mode server php_version status
    file="$(plume_sites_file "${site_id}")"
    path="$(plume_sites_record_value "${file}" path)"
    mode="$(plume_site_record_mode "${site_id}" || true)"
    server="$(plume_sites_record_value "${file}" server)"
    php_version="$(plume_sites_record_php_version "${file}")"
    status="$(plume_sites_record_value "${file}" status)"
    [[ -n "${mode}" ]] || mode="-"
    [[ -n "${server}" ]] || server="-"
    [[ -n "${php_version}" ]] || php_version="-"
    [[ -n "${status}" ]] || status="-"
    [[ -n "${path}" ]] || path="-"
    rows+=("${site_id}"$'\t'"${mode}"$'\t'"${server}"$'\t'"${php_version}"$'\t'"${status}"$'\t'"${path}")
    (( ${#site_id} > width_id )) && width_id="${#site_id}"
    (( ${#mode} > width_mode )) && width_mode="${#mode}"
    (( ${#server} > width_server )) && width_server="${#server}"
    (( ${#php_version} > width_php )) && width_php="${#php_version}"
    (( ${#status} > width_status )) && width_status="${#status}"
    (( ${#path} > width_path )) && width_path="${#path}"
  done < <(plume_sites_index_ids)

  local total_width=$((width_id + width_mode + width_server + width_php + width_status + width_path + 10))
  printf "%-${width_id}s  %-${width_mode}s  %-${width_server}s  %-${width_php}s  %-${width_status}s  %-${width_path}s\n" \
    "${header_id}" "${header_mode}" "${header_server}" "${header_php}" "${header_status}" "${header_path}"
  printf '%s\n' "$(printf '%*s' "${total_width}" '' | tr ' ' '-')"

  local row
  if (( ${#rows[@]} > 0 )); then
    for row in "${rows[@]}"; do
      IFS=$'\t' read -r site_id mode server php_version status path <<< "${row}"
      printf "%-${width_id}s  %-${width_mode}s  %-${width_server}s  %-${width_php}s  %-${width_status}s  %-${width_path}s\n" \
        "${site_id}" "${mode}" "${server}" "${php_version}" "${status}" "${path}"
    done
  fi
}

cmd_site_publish() {
  local site_id="${1:-}"
  shift || true
  local resolved_mode dry_run

  if [[ -z "${site_id}" ]]; then
    plume_err "site id required"
    return 2
  fi

  plume_site_parse_args "$@" || return 2
  dry_run="${PLUME_SITE_DRY_RUN}"

  if ! plume_sites_exists "${site_id}"; then
    plume_err "site not found: ${site_id}"
    return 2
  fi

  resolved_mode="$(plume_site_record_mode "${site_id}")"
  if [[ -z "${resolved_mode}" ]]; then
    resolved_mode="$(plume_site_resolve_mode "${PLUME_SITE_MODE:-}" "" "${PLUME_MODE_HINT:-}")"
  fi

  if ! plume_site_validate_mode "${resolved_mode}"; then
    plume_err "invalid mode: ${resolved_mode}"
    return 2
  fi

  if [[ "${dry_run}" == "true" ]]; then
    local file server path port domains
    file="$(plume_sites_file "${site_id}")"
    server="$(plume_sites_record_value "${file}" server)"
    path="$(plume_sites_record_value "${file}" path)"
    port="$(plume_sites_record_port "${file}")"
