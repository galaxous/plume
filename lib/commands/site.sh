cmd_site() {
  local mode="${PLUME_MODE:-$(plume_mode_current)}"
  local -a args=()
  local waiting_mode_value="false"
  local arg
  local mode_set="false"

  for arg in "$@"; do
    if [[ "${waiting_mode_value}" == "true" ]]; then
      mode="${arg}"
      mode_set="true"
      waiting_mode_value="false"
      continue
    fi

    case "${arg}" in
      --mode=*)
        mode_set="true"
        mode="${arg#*=}"
        ;;
      --mode)
        waiting_mode_value="true"
        ;;
      *)
        args+=("${arg}")
        ;;
    esac
  done

  if [[ "${waiting_mode_value}" == "true" ]]; then
    plume_err "--mode requires a value"
    return 2
  fi

  case "${mode}" in
    native|docker-lite|laradock-bridge) ;;
    *)
      plume_err "invalid mode: ${mode}"
      return 2
      ;;
  esac

  if (( ${#args[@]} > 0 )); then
    set -- "${args[@]}"
  else
    set --
  fi
  if [[ "${mode_set}" == "true" ]]; then
    PLUME_MODE_HINT="${mode}"
  else
    unset PLUME_MODE_HINT || true
  fi
  local sub="${1:-list}"
  shift || true
  case "${sub}" in
    add)
      PLUME_MODE="${mode}" cmd_site_add "$@"
      ;;
    update)
      PLUME_MODE="${mode}" cmd_site_update "$@"
      ;;
    publish)
      PLUME_MODE="${mode}" cmd_site_publish "$@"
      ;;
    list)
      PLUME_MODE="${mode}" cmd_site_list "$@"
      ;;
    modes)
      PLUME_MODE="${mode}" cmd_site_modes "$@"
      ;;
    check)
      PLUME_MODE="${mode}" cmd_site_check "${1:-}"
      ;;
    remove)
      PLUME_MODE="${mode}" cmd_site_remove "$@"
      ;;
    help|--help|-h)
      plume_site_usage
      ;;
    *)
      plume_err "unknown site subcommand: ${sub}"
      plume_site_usage
      return 2
      ;;
  esac
}
