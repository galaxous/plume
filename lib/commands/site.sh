    plume_site_plan_print "publish" "${site_id}" "${resolved_mode}" "${path}" "${server}" "${port}" "${domains}" "$(plume_sites_record_php_version "${file}")"
    return 0
  fi

  if ! plume_sites_publish_nginx "${site_id}" "${resolved_mode}"; then
    plume_err "publish failed"
    return 2
  fi

  if [[ "${PLUME_SITE_RELOAD}" == "true" ]]; then
    if [[ "${PLUME_SITE_LAST_PUBLISH_RELOADED:-false}" == "true" ]]; then
      plume_info "site reload skipped: already reloaded in strict publish pipeline"
    else
    local server
    server="$(plume_sites_record_value "$(plume_sites_file "${site_id}")" server)"
    if ! plume_sites_reload_nginx "${site_id}" "${resolved_mode}"; then
      if [[ "$(plume_bool "${PLUME_SITE_RELOAD_REQUIRED:-false}")" == "true" ]]; then
        plume_err "publish succeeded but ${server} reload failed"
        return 2
      fi
      plume_warn "publish succeeded but ${server} reload failed"
    fi
    fi
  fi

  if [[ "${PLUME_OUTPUT:-text}" == "json" ]]; then
    printf '{"ok":true,"command":"site publish","data":{"id":"%s","reload":%s},"warnings":[],"errors":[]}\n' \
      "${site_id}" "${PLUME_SITE_RELOAD}"
  else
    plume_info "site published: ${site_id}"
  fi
}

