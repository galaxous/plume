cmd_site_check() {
  local site_id="${1:-}"
  if [[ -z "${site_id}" ]]; then
    plume_err "site id required"
    return 2
  fi

  if ! plume_sites_exists "${site_id}"; then
    plume_err "site not found: ${site_id}"
    return 2
  fi

  local file="" path="" server="" php_version="" php_upstream="" resolved_upstream="" port="" https_port="" cert_id="" status="" document_root="" server_config=""
  local mode="" strict_enabled="false" strict_include_dir="" strict_include_target=""
  local effective_http_port="" first_domain="" url_http="" url_https="" access_hint="" json_warnings=""
  file="$(plume_sites_file "${site_id}")"
  mode="$(plume_site_record_mode "${site_id}" || true)"
  [[ -n "${mode}" ]] || mode="$(plume_mode_current)"
  path="$(plume_sites_record_value "${file}" path)"
  server="$(plume_sites_record_value "${file}" server)"
  php_version="$(plume_sites_record_php_version "${file}")"
  php_upstream="$(plume_sites_record_php_upstream "${file}")"
  if [[ -n "${php_upstream}" ]]; then
    resolved_upstream="${php_upstream}"
  else
    resolved_upstream="$(plume_sites_php_upstream_for_version "${mode}" "${php_version}")"
  fi
  port="$(plume_sites_record_port "${file}")"
  https_port="$(plume_sites_record_https_port "${file}")"
  cert_id="$(plume_sites_record_cert_id "${file}")"
  first_domain="$(plume_sites_record_domains "${file}" | head -n 1)"
  [[ -n "${first_domain}" ]] || first_domain="localhost"
  effective_http_port="$(plume_sites_effective_http_port "${port}" "${mode}")"
  url_http="$(plume_sites_format_public_url "http" "${first_domain}" "${effective_http_port}")"
  if [[ -n "${cert_id}" ]]; then
    [[ -n "${https_port}" ]] || https_port="443"
    url_https="$(plume_sites_format_public_url "https" "${first_domain}" "${https_port}")"
  fi
  access_hint="$(plume_sites_access_hint_for_http "${port}" "${effective_http_port}" "${url_http}")"
  if [[ -n "${access_hint}" ]]; then
    json_warnings="\"$(printf '%s' "${access_hint}" | sed 's/\\/\\\\/g; s/"/\\"/g')\""
  fi
  local tcc_risk="false"
  if plume_sites_path_is_macos_tcc_sensitive "${path}"; then
    tcc_risk="true"
    local tcc_hint=""
    if declare -F plume_macos_permissions_site_tcc_hint >/dev/null 2>&1; then
      tcc_hint="$(plume_macos_permissions_site_tcc_hint "${path}")"
    else
      tcc_hint="macOS TCC: Desktop/Documents/Downloads path may block nginx/php-fpm (No input file specified). See site.md."
    fi
    if [[ -n "${json_warnings}" ]]; then
      json_warnings="${json_warnings},\"$(printf '%s' "${tcc_hint}" | sed 's/\\/\\\\/g; s/"/\\"/g')\""
    else
      json_warnings="\"$(printf '%s' "${tcc_hint}" | sed 's/\\/\\\\/g; s/"/\\"/g')\""
    fi
  fi
  status="$(plume_sites_record_value "${file}" status)"
  document_root="$(plume_sites_record_value "${file}" document_root)"
  server_config="$(plume_sites_record_server_config "${file}")"

  if [[ "${mode}" == "native" ]]; then
    case "${server}" in
      nginx)
        if [[ "$(plume_bool "${PLUME_SITE_NGINX_STRICT:-false}")" == "true" ]]; then
          strict_enabled="true"
        fi
        ;;
      apache2)
        if [[ "$(plume_bool "${PLUME_SITE_APACHE2_STRICT:-false}")" == "true" ]]; then
          strict_enabled="true"
        fi
        ;;
      caddy)
        if [[ "$(plume_bool "${PLUME_SITE_CADDY_STRICT:-false}")" == "true" ]]; then
          strict_enabled="true"
        fi
        ;;
    esac
    strict_include_dir="$(plume_sites_native_include_dir_for_server "${server}" || true)"
    if [[ -n "${strict_include_dir}" ]]; then
      strict_include_target="${strict_include_dir}/${site_id}.conf"
    fi
  fi

  if [[ "${PLUME_OUTPUT:-text}" == "json" ]]; then
    printf '{"ok":true,"command":"site check","data":{"id":"%s","mode":"%s","path":"%s","server":"%s","php_version":"%s","php_upstream":"%s","php_upstream_resolved":"%s","strict_enabled":%s,"strict_include_dir":"%s","strict_include_target":"%s","port":%s,"effective_http_port":%s,"https_port":%s,"url_http":"%s","url_https":"%s","access_hint":"%s","tcc_risk":%s,"cert_id":"%s","status":"%s","document_root":"%s","server_config":"%s","domains":[' \
      "${site_id}" "${mode}" "${path}" "${server}" "${php_version}" "${php_upstream}" "${resolved_upstream}" "${strict_enabled}" "${strict_include_dir}" "${strict_include_target}" "${port}" "${effective_http_port}" "${https_port}" "${url_http}" "${url_https}" "$(printf '%s' "${access_hint}" | sed 's/\\/\\\\/g; s/"/\\"/g')" "${tcc_risk}" "${cert_id}" "${status}" "${document_root}" "${server_config}"
    local first="true"
    local domain
    while IFS= read -r domain; do
      if [[ "${first}" == "true" ]]; then
        first="false"
      else
        printf ','
      fi
      printf '"%s"' "${domain}"
    done < <(plume_sites_record_domains "${file}")
    if [[ -n "${json_warnings}" ]]; then
      printf ']},"warnings":[%s],"errors":[]}\n' "${json_warnings}"
    else
      printf ']},"warnings":[],"errors":[]}\n'
    fi
    return 0
  fi

  printf '%s\n' "site: ${site_id}"
  printf '%s\n' "mode: ${mode}"
  printf '%s\n' "path: ${path}"
  printf '%s\n' "server: ${server}"
  printf '%s\n' "php_version: ${php_version}"
  printf '%s\n' "php_upstream: ${php_upstream}"
  printf '%s\n' "php_upstream_resolved: ${resolved_upstream}"
  printf '%s\n' "strict_enabled: ${strict_enabled}"
  printf '%s\n' "strict_include_dir: ${strict_include_dir}"
  printf '%s\n' "strict_include_target: ${strict_include_target}"
  printf '%s\n' "port: ${port}"
  printf '%s\n' "effective_http_port: ${effective_http_port}"
  printf '%s\n' "https_port: ${https_port}"
  printf '%s\n' "url_http: ${url_http}"
  if [[ -n "${url_https}" ]]; then
    printf '%s\n' "url_https: ${url_https}"
  fi
  if [[ -n "${access_hint}" ]]; then
    printf '%s\n' "access_hint: ${access_hint}"
  fi
  if [[ "${tcc_risk}" == "true" ]]; then
    printf '%s\n' "tcc_risk: true"
    if declare -F plume_macos_permissions_site_tcc_hint >/dev/null 2>&1; then
      printf '%s\n' "tcc_hint: $(plume_macos_permissions_site_tcc_hint "${path}")"
    else
      printf '%s\n' "tcc_hint: macOS Desktop/Documents/Downloads — grant Full Disk Access to nginx/php-fpm or move project (site.md)"
    fi
  fi
  printf '%s\n' "cert_id: ${cert_id}"
  printf '%s\n' "status: ${status}"
  printf '%s\n' "document_root: ${document_root}"
  printf '%s\n' "server_config: ${server_config}"
  printf 'domains: '
  plume_sites_record_domains "${file}"
}

