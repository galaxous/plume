#!/usr/bin/env bash
set -euo pipefail

plume_host_profile_file() {
  printf '%s' "${PLUME_HOST_PROFILE_FILE:-$HOME/.config/plume/host.env}"
}

plume_host_profile_exists() {
  [[ -f "$(plume_host_profile_file)" ]]
}

plume_host_profile_detect_os_version() {
  local os
  os="$(plume_detect_os)"
  case "${os}" in
    macos)
      sw_vers -productVersion 2>/dev/null || echo "unknown"
      ;;
    linux)
      if [[ -f /etc/os-release ]]; then
        # shellcheck disable=SC1091
        . /etc/os-release
        printf '%s' "${VERSION_ID:-${PRETTY_NAME:-unknown}}"
      else
        echo "unknown"
      fi
      ;;
    windows)
      cmd.exe /c ver 2>/dev/null | tr -d '\r' || echo "unknown"
      ;;
    *)
      echo "unknown"
      ;;
  esac
}

plume_host_profile_detect_arch() {
  uname -m 2>/dev/null || echo "unknown"
}

plume_host_profile_web_driver_hint() {
  case "${PLUME_WEB_SERVER_DRIVER:-nginx}" in
    nginx|apache2|caddy) printf '%s' "${PLUME_WEB_SERVER_DRIVER:-nginx}" ;;
    *) printf '%s' "nginx" ;;
  esac
}

plume_host_profile_homebrew_nginx() {
  if [[ "$(plume_detect_os)" != "macos" ]]; then
    printf 'false'
    return 0
  fi
  if command -v brew >/dev/null 2>&1; then
    if HOMEBREW_NO_AUTO_UPDATE=1 brew list nginx >/dev/null 2>&1; then
      printf 'true'
      return 0
    fi
  fi
  if [[ -f "/opt/homebrew/etc/nginx/nginx.conf" || -f "/usr/local/etc/nginx/nginx.conf" ]]; then
    printf 'true'
    return 0
  fi
  printf 'false'
}

plume_host_profile_nginx_http_port_detected() {
  if declare -F plume_native_nginx_main_listen_port >/dev/null 2>&1; then
    local port=""
    port="$(plume_native_nginx_main_listen_port 2>/dev/null || true)"
    if [[ -n "${port}" ]]; then
      printf '%s' "${port}"
      return 0
    fi
  fi
  printf '%s' ""
}

plume_host_profile_native_support_note() {
  case "$(plume_detect_os)" in
    windows) printf '%s' "limited native mode (profile only; full native web/nginx not supported on Windows yet)" ;;
    *) printf '%s' "" ;;
  esac
}

plume_host_profile_read_value() {
  local key="$1"
  local file
  file="$(plume_host_profile_file)"
  [[ -f "${file}" ]] || return 1
  awk -F= -v k="${key}" '$1==k {print substr($0, index($0, "=")+1); exit}' "${file}" 2>/dev/null || true
}

plume_host_profile_set_value() {
  local key="$1"
  local value="$2"
  local file tmp
  file="$(plume_host_profile_file)"
  mkdir -p "$(dirname "${file}")"
  touch "${file}"
  if grep -q "^${key}=" "${file}" 2>/dev/null; then
    tmp="$(mktemp)"
    awk -F= -v k="${key}" -v v="${value}" '
      $1==k { print k "=" v; next }
      { print }
    ' "${file}" > "${tmp}"
    mv "${tmp}" "${file}"
  else
    printf '%s=%s\n' "${key}" "${value}" >> "${file}"
  fi
}

plume_host_profile_detect_and_persist() {
  local force="${1:-false}"
  local file
  file="$(plume_host_profile_file)"

  if [[ "${force}" != "true" ]] && [[ -f "${file}" ]]; then
    plume_info "host profile already present: ${file} (use --force to refresh)"
    return 0
  fi

  local os os_version arch pm web_hint nginx_port homebrew_nginx state_dir detected_at support_note
  os="$(plume_detect_os)"
  os_version="$(plume_host_profile_detect_os_version)"
  arch="$(plume_host_profile_detect_arch)"
  pm="$(plume_detect_package_manager)"
  web_hint="$(plume_host_profile_web_driver_hint)"
  nginx_port="$(plume_host_profile_nginx_http_port_detected)"
  homebrew_nginx="$(plume_host_profile_homebrew_nginx)"
  state_dir="${PLUME_STATE_DIR:-$HOME/.config/plume/state}"
  detected_at="$(date -u +"%Y-%m-%dT%H:%M:%SZ" 2>/dev/null || date -u)"
  support_note="$(plume_host_profile_native_support_note)"

  mkdir -p "$(dirname "${file}")"
  {
    printf '# Plume host profile (generated by plumectl init host / auto-bootstrap)\n'
    printf 'os=%s\n' "${os}"
    printf 'os_version=%s\n' "${os_version}"
    printf 'arch=%s\n' "${arch}"
    printf 'package_manager=%s\n' "${pm}"
    printf 'web_driver_hint=%s\n' "${web_hint}"
    printf 'nginx_http_port_detected=%s\n' "${nginx_port:-}"
    printf 'homebrew_nginx=%s\n' "${homebrew_nginx}"
    printf 'state_dir=%s\n' "${state_dir}"
    printf 'detected_at=%s\n' "${detected_at}"
    if [[ -n "${support_note}" ]]; then
      printf 'native_support_note=%s\n' "${support_note}"
    fi
  } > "${file}"

  plume_info "host profile written: ${file}"
}

plume_host_profile_maybe_autobootstrap() {
  if [[ "$(plume_bool "${PLUME_AUTO_HOST_BOOTSTRAP:-true}")" != "true" ]]; then
    return 0
  fi
  if plume_host_profile_exists; then
    return 0
  fi
  plume_host_profile_detect_and_persist "false" >/dev/null 2>&1 || true
}
