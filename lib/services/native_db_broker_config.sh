plume_native_postgres_apply_password() {
  local pass user port
  pass="$(plume_native_postgres_effective_password)"
  user="${PLUME_POSTGRES_USER:-postgres}"
  port="$(plume_native_driver_default_port postgres)"
  [[ -n "${pass}" ]] || return 0
  command -v psql >/dev/null 2>&1 || return 0
  if PGPASSWORD="${pass}" psql -h127.0.0.1 -p"${port}" -U"${user}" -d postgres -c "SELECT 1" >/dev/null 2>&1; then
    return 0
  fi
  if psql -h127.0.0.1 -p"${port}" -U"${user}" -d postgres -c "SELECT 1" >/dev/null 2>&1; then
    psql -h127.0.0.1 -p"${port}" -U"${user}" -d postgres -c \
      "ALTER USER ${user} WITH PASSWORD '${pass}';" >/dev/null 2>&1 || true
  fi
}

