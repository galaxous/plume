plume_native_mongodb_write_block() {
  local port bind user pass db auth_enabled
  port="$(plume_native_driver_default_port mongodb)"
  bind="${PLUME_NATIVE_MONGODB_BIND:-127.0.0.1}"
  user="${PLUME_MONGODB_USERNAME:-root}"
  pass="${PLUME_MONGODB_PASSWORD:-example}"
  db="${PLUME_MONGODB_DATABASE:-admin}"
  auth_enabled="enabled"
  if [[ -z "${pass}" || "${pass}" == "null" ]]; then
    auth_enabled="disabled"
  fi
  printf '%s\n' "net:"
  printf '  port: %s\n' "${port}"
  printf '  bindIp: %s\n' "${bind}"
  printf '%s\n' "security:"
  printf '  authorization: %s\n' "${auth_enabled}"
  printf '%s\n' "# plume user: ${user} db: ${db}"
}

