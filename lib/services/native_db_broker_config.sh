plume_native_mongodb_apply_auth() {
  local user pass port db
  user="${PLUME_MONGODB_USERNAME:-root}"
  pass="${PLUME_MONGODB_PASSWORD:-example}"
  port="$(plume_native_driver_default_port mongodb)"
  db="${PLUME_MONGODB_DATABASE:-admin}"
  [[ -n "${pass}" && "${pass}" != "null" ]] || return 0
  local mongo_cli=""
  if command -v mongosh >/dev/null 2>&1; then
    mongo_cli="mongosh"
  elif command -v mongo >/dev/null 2>&1; then
    mongo_cli="mongo"
  else
    return 0
  fi
  "${mongo_cli}" --quiet --port "${port}" --eval \
    "db.getSiblingDB('${db}').getUser('${user}') || db.getSiblingDB('${db}').createUser({user:'${user}',pwd:'${pass}',roles:[{role:'root',db:'${db}'}]})" \
    >/dev/null 2>&1 || true
}

