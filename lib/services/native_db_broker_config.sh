plume_native_rabbitmq_write_block() {
  local port mgmt_port user pass
  port="${PLUME_RABBITMQ_PORT:-5672}"
  mgmt_port="${PLUME_RABBITMQ_MANAGEMENT_PORT:-15672}"
  user="${PLUME_RABBITMQ_USER:-guest}"
  pass="${PLUME_RABBITMQ_PASSWORD:-guest}"
  printf 'listeners.tcp.default = %s\n' "${port}"
  printf 'management.tcp.port = %s\n' "${mgmt_port}"
  printf 'default_user = %s\n' "${user}"
  printf 'default_pass = %s\n' "${pass}"
}

plume_native_rabbitmq_sync_config() {
  local dry_run="${1:-false}"
  local do_reload="${2:-false}"
  local main_conf block

  if ! plume_native_stack_config_manage_enabled rabbitmq; then
    plume_err "Set PLUME_NATIVE_RABBITMQ_MANAGE_CONFIG=true to apply native rabbitmq config"
    return 2
  fi

  main_conf="$(plume_native_rabbitmq_main_conf_path)"
  block="$(plume_native_rabbitmq_write_block)"

  if plume_native_driver_is_mock; then
    if [[ "${dry_run}" == "true" ]]; then
      printf 'action: rabbitmq-sync-config\n'
      return 0
    fi
    if [[ -n "${main_conf}" && -f "${main_conf}" ]]; then
      plume_native_stack_config_replace_block "${main_conf}" "${block}"
    fi
    [[ "${do_reload}" == "true" ]] && plume_native_stack_config_reload_service rabbitmq || true
    return 0
  fi

  if [[ -z "${main_conf}" || ! -f "${main_conf}" ]]; then
    mkdir -p "$(dirname "${main_conf:-/etc/rabbitmq/rabbitmq.conf}")" 2>/dev/null || true
    if [[ -z "${main_conf}" ]]; then
      main_conf="/opt/homebrew/etc/rabbitmq/rabbitmq.conf"
    fi
    if [[ ! -f "${main_conf}" ]]; then
      plume_err "rabbitmq main config not found (install rabbitmq, e.g. brew install rabbitmq)"
      return 2
    fi
  fi

  if [[ "${dry_run}" == "true" ]]; then
    printf 'action: rabbitmq-sync-config\n'
    printf 'main_conf: %s\n' "${main_conf}"
    return 0
  fi

  plume_native_stack_config_replace_block "${main_conf}" "${block}"
  if [[ "${do_reload}" == "true" ]]; then
    plume_native_stack_config_reload_service rabbitmq || return 2
    plume_native_rabbitmq_apply_users || true
  else
    plume_info "restart rabbitmq to apply: ./plume.sh services restart rabbitmq --mode=native"
  fi
}

plume_native_rabbitmq_apply_users() {
  local user pass
  user="${PLUME_RABBITMQ_USER:-guest}"
  pass="${PLUME_RABBITMQ_PASSWORD:-guest}"
  command -v rabbitmqctl >/dev/null 2>&1 || return 0
  if rabbitmqctl authenticate_user "${user}" "${pass}" >/dev/null 2>&1; then
    return 0
  fi
  rabbitmqctl add_user "${user}" "${pass}" >/dev/null 2>&1 \
    || rabbitmqctl change_password "${user}" "${pass}" >/dev/null 2>&1 || true
  rabbitmqctl set_user_tags "${user}" administrator >/dev/null 2>&1 || true
  rabbitmqctl set_permissions -p / "${user}" ".*" ".*" ".*" >/dev/null 2>&1 || true
}
