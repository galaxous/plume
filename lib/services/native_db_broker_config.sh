#!/usr/bin/env bash
set -euo pipefail

# Native MariaDB/MySQL, Postgres, MongoDB, RabbitMQ config from PLUME_* env.

plume_native_mariadb_plume_conf_path() {
  local service="$1"
  printf '%s/native/%s/plume-%s.cnf' "$(plume_state_dir)" "${service}" "${service}"
}

plume_native_mariadb_main_conf_path() {
  if [[ -n "${PLUME_NATIVE_MARIADB_MAIN_CONF:-}" ]]; then
    printf '%s' "${PLUME_NATIVE_MARIADB_MAIN_CONF}"
    return 0
  fi
  local candidate prefix
  for candidate in \
    /opt/homebrew/etc/my.cnf \
    /usr/local/etc/my.cnf \
    /etc/my.cnf \
    /etc/mysql/my.cnf; do
    if [[ -f "${candidate}" ]]; then
      printf '%s' "${candidate}"
      return 0
    fi
  done
  if command -v brew >/dev/null 2>&1; then
    prefix="$(HOMEBREW_NO_AUTO_UPDATE=1 brew --prefix mariadb 2>/dev/null || true)"
    if [[ -n "${prefix}" && -f "${prefix}/etc/my.cnf" ]]; then
      printf '%s' "${prefix}/etc/my.cnf"
      return 0
    fi
  fi
  printf '%s' ""
}

plume_native_mariadb_effective_root_password() {
  local service="$1"
  case "${service}" in
    mysql)
      plume_native_stack_effective_password "${PLUME_MYSQL_ROOT_PASSWORD-__PLUME_UNSET__}" "root"
      ;;
    *)
      plume_native_stack_effective_password "${PLUME_MARIADB_ROOT_PASSWORD-__PLUME_UNSET__}" "root"
      ;;
  esac
}

plume_native_mariadb_effective_port() {
  local service="$1"
  case "${service}" in
    mysql) printf '%s' "${PLUME_MYSQL_PORT:-3306}" ;;
    *) printf '%s' "$(plume_native_driver_default_port mariadb)" ;;
  esac
}

plume_native_mariadb_write_plume_conf() {
  local service="$1"
  local port bind plume_conf
  port="$(plume_native_mariadb_effective_port "${service}")"
  bind="${PLUME_NATIVE_MARIADB_BIND:-127.0.0.1}"
  plume_conf="$(plume_native_mariadb_plume_conf_path "${service}")"
  mkdir -p "$(dirname "${plume_conf}")"
  {
    printf '%s\n' '# Generated by Plume — PLUME_MARIADB_* / PLUME_MYSQL_*'
    printf '%s\n' '[mysqld]'
    printf 'port=%s\n' "${port}"
    printf 'bind-address=%s\n' "${bind}"
  } > "${plume_conf}"
  plume_info "native ${service}: wrote ${plume_conf}"
}

plume_native_mariadb_sync_config() {
  local service="$1"
  local dry_run="${2:-false}"
  local do_reload="${3:-false}"
  local main_conf plume_conf port

  if ! plume_native_stack_config_manage_enabled "${service}"; then
    plume_err "Set PLUME_NATIVE_${service}_MANAGE_CONFIG=true to apply native ${service} config"
    return 2
  fi

  main_conf="$(plume_native_mariadb_main_conf_path)"
  plume_conf="$(plume_native_mariadb_plume_conf_path "${service}")"
  port="$(plume_native_mariadb_effective_port "${service}")"

  if plume_native_driver_is_mock; then
    if [[ "${dry_run}" == "true" ]]; then
      printf 'action: %s-sync-config\n' "${service}"
      printf 'plume_conf: %s\n' "${plume_conf}"
      printf 'port: %s\n' "${port}"
      return 0
    fi
    plume_native_mariadb_write_plume_conf "${service}"
    # Hermetic smoke sets PLUME_NATIVE_MARIADB_MAIN_CONF to a temp file.
    # Never mutate real Homebrew /etc/my.cnf under mock lifecycle (D-134/D-137).
    if [[ -n "${PLUME_NATIVE_MARIADB_MAIN_CONF:-}" && -f "${main_conf}" ]]; then
      plume_native_stack_config_ensure_include "${main_conf}" "!include ${plume_conf}"
    fi
    [[ "${do_reload}" == "true" ]] && plume_native_stack_config_reload_service "${service}" || true
    return 0
  fi

  if [[ -z "${main_conf}" || ! -f "${main_conf}" ]]; then
    plume_err "${service} main config not found (install ${service}, e.g. brew install ${service})"
    return 2
  fi

  if [[ "${dry_run}" == "true" ]]; then
    printf 'action: %s-sync-config\n' "${service}"
    printf 'main_conf: %s\n' "${main_conf}"
    printf 'plume_conf: %s\n' "${plume_conf}"
    printf 'port: %s\n' "${port}"
    return 0
  fi

  plume_native_mariadb_write_plume_conf "${service}"
  plume_native_stack_config_ensure_include "${main_conf}" "!include ${plume_conf}"
  if [[ "${do_reload}" == "true" ]]; then
    plume_native_stack_config_reload_service "${service}" || return 2
    plume_native_mariadb_apply_root_password "${service}" || true
  else
    plume_info "restart ${service} to apply: ./plume.sh services restart ${service} --mode=native"
  fi
}

plume_native_mariadb_socket_path() {
  local candidate prefix
  for candidate in \
    /opt/homebrew/var/mysql/mysql.sock \
    /opt/homebrew/var/run/mysqld/mysqld.sock \
    /usr/local/var/mysql/mysql.sock \
    /tmp/mysql.sock; do
    if [[ -S "${candidate}" ]]; then
      printf '%s' "${candidate}"
      return 0
    fi
  done
  if command -v brew >/dev/null 2>&1; then
    prefix="$(HOMEBREW_NO_AUTO_UPDATE=1 brew --prefix mariadb 2>/dev/null \
      || HOMEBREW_NO_AUTO_UPDATE=1 brew --prefix mysql 2>/dev/null \
      || true)"
    if [[ -n "${prefix}" && -S "${prefix}/var/mysql/mysql.sock" ]]; then
      printf '%s' "${prefix}/var/mysql/mysql.sock"
      return 0
    fi
  fi
  return 1
}

plume_native_mariadb_apply_root_password() {
  local service="$1"
  local pass port sock
  if plume_native_driver_is_mock 2>/dev/null; then
    return 0
  fi
  pass="$(plume_native_mariadb_effective_root_password "${service}")"
  port="$(plume_native_mariadb_effective_port "${service}")"
  [[ -n "${pass}" ]] || return 0
  command -v mysql >/dev/null 2>&1 || return 0
  # Never open /dev/tty for password prompts (CI/smoke); stdin closed.
  if mysql -uroot -h127.0.0.1 -P"${port}" -p"${pass}" --connect-expired-password --batch -e "SELECT 1" </dev/null >/dev/null 2>&1; then
    return 0
  fi
  sock="$(plume_native_mariadb_socket_path 2>/dev/null || true)"
  if [[ -n "${sock}" ]]; then
    if mysql -uroot --socket="${sock}" --batch -e "SELECT 1" </dev/null >/dev/null 2>&1; then
      mysql -uroot --socket="${sock}" --batch -e \
        "ALTER USER 'root'@'localhost' IDENTIFIED BY '${pass}'; FLUSH PRIVILEGES;" </dev/null >/dev/null 2>&1 || true
    fi
  fi
  return 0
}

plume_native_postgres_plume_conf_path() {
  printf '%s/native/postgres/plume-postgres.conf' "$(plume_state_dir)"
}

plume_native_postgres_main_conf_path() {
  if [[ -n "${PLUME_NATIVE_POSTGRES_MAIN_CONF:-}" ]]; then
    printf '%s' "${PLUME_NATIVE_POSTGRES_MAIN_CONF}"
    return 0
  fi
  local candidate ver prefix
  for candidate in \
    /opt/homebrew/var/postgresql@16/postgresql.conf \
    /opt/homebrew/var/postgresql@15/postgresql.conf \
    /opt/homebrew/var/postgres/postgresql.conf \
    /usr/local/var/postgresql@16/postgresql.conf; do
    if [[ -f "${candidate}" ]]; then
      printf '%s' "${candidate}"
      return 0
    fi
  done
  if compgen -G "/etc/postgresql/*/main/postgresql.conf" >/dev/null 2>&1; then
    for candidate in /etc/postgresql/*/main/postgresql.conf; do
      if [[ -f "${candidate}" ]]; then
        printf '%s' "${candidate}"
        return 0
      fi
    done
  fi
  if command -v brew >/dev/null 2>&1; then
    for ver in 16 15 14; do
      prefix="$(HOMEBREW_NO_AUTO_UPDATE=1 brew --prefix "postgresql@${ver}" 2>/dev/null || true)"
      if [[ -n "${prefix}" && -f "${prefix}/var/postgresql@${ver}/postgresql.conf" ]]; then
        printf '%s' "${prefix}/var/postgresql@${ver}/postgresql.conf"
        return 0
      fi
    done
  fi
  printf '%s' ""
}

plume_native_postgres_effective_password() {
  plume_native_stack_effective_password "${PLUME_POSTGRES_PASSWORD-__PLUME_UNSET__}" "postgres"
}

plume_native_postgres_write_plume_conf() {
