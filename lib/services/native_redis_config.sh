#!/usr/bin/env bash
set -euo pipefail

# Native Redis: apply PLUME_REDIS_* to a plume-managed include + system redis.conf hook.

plume_native_redis_manage_config_enabled() {
  [[ "$(plume_bool "${PLUME_NATIVE_REDIS_MANAGE_CONFIG:-true}")" == "true" ]]
}

plume_native_redis_plume_conf_path() {
  printf '%s/native/redis/plume-redis.conf' "$(plume_state_dir)"
}

plume_native_redis_include_marker_begin() {
  printf '%s' '# >>> plume-managed include >>>'
}

plume_native_redis_include_marker_end() {
  printf '%s' '# <<< plume-managed include <<<'
}

plume_native_redis_main_conf_path() {
  if [[ -n "${PLUME_NATIVE_REDIS_MAIN_CONF:-}" ]]; then
    printf '%s' "${PLUME_NATIVE_REDIS_MAIN_CONF}"
    return 0
  fi
  local candidate prefix
  for candidate in \
    /opt/homebrew/etc/redis.conf \
    /usr/local/etc/redis.conf \
    /etc/redis/redis.conf \
    /etc/redis.conf; do
    if [[ -f "${candidate}" ]]; then
      printf '%s' "${candidate}"
      return 0
    fi
  done
  if command -v brew >/dev/null 2>&1; then
    prefix="$(HOMEBREW_NO_AUTO_UPDATE=1 brew --prefix redis 2>/dev/null || true)"
    if [[ -n "${prefix}" && -f "${prefix}/etc/redis.conf" ]]; then
      printf '%s' "${prefix}/etc/redis.conf"
      return 0
    fi
  fi
  printf '%s' ""
}

plume_native_redis_effective_password() {
  local pass="${PLUME_REDIS_PASSWORD-__PLUME_UNSET__}"
  if [[ "${pass}" == "__PLUME_UNSET__" ]]; then
    pass="secret_redis"
  fi
  case "${pass}" in
    ""|null|NULL|none|NONE|false|FALSE)
      printf '%s' ""
      ;;
    *)
      printf '%s' "${pass}"
      ;;
  esac
}

plume_native_redis_effective_bind() {
  printf '%s' "${PLUME_NATIVE_REDIS_BIND:-127.0.0.1}"
}

plume_native_redis_effective_port() {
  if declare -F plume_service_effective_port >/dev/null 2>&1; then
    plume_service_effective_port redis native
  else
    plume_native_driver_default_port redis
  fi
}

plume_native_redis_write_plume_conf() {
  local port password bind plume_conf
  port="$(plume_native_redis_effective_port)"
  password="$(plume_native_redis_effective_password)"
  bind="$(plume_native_redis_effective_bind)"
  plume_conf="$(plume_native_redis_plume_conf_path)"
  mkdir -p "$(dirname "${plume_conf}")"

  {
    printf '%s\n' '# Generated by Plume — do not edit (use PLUME_REDIS_* / services redis sync-config)'
    printf 'port %s\n' "${port}"
    printf 'bind %s\n' "${bind}"
    printf 'protected-mode yes\n'
    if [[ -n "${password}" ]]; then
      printf 'requirepass %s\n' "${password}"
    fi
  } > "${plume_conf}"
  plume_info "native redis: wrote ${plume_conf}"
}

plume_native_redis_ensure_include() {
  local main_conf plume_conf begin end tmp backup
  main_conf="$(plume_native_redis_main_conf_path)"
  plume_conf="$(plume_native_redis_plume_conf_path)"
  begin="$(plume_native_redis_include_marker_begin)"
  end="$(plume_native_redis_include_marker_end)"

  if [[ -z "${main_conf}" || ! -f "${main_conf}" ]]; then
    plume_err "redis main config not found (install redis, e.g. brew install redis)"
    return 2
  fi

  if grep -Fq "${begin}" "${main_conf}" 2>/dev/null; then
    tmp="$(mktemp)"
    awk -v begin="${begin}" -v end="${end}" -v inc="${plume_conf}" '
      $0 ~ begin { skip=1; print begin; print "include " inc; print end; next }
      skip && $0 ~ end { skip=0; next }
      !skip { print }
    ' "${main_conf}" > "${tmp}"
    if ! cmp -s "${main_conf}" "${tmp}"; then
      backup="${main_conf}.plume-backup-$(date +%Y%m%d%H%M%S)"
      cp "${main_conf}" "${backup}"
      mv "${tmp}" "${main_conf}"
      plume_info "native redis: updated include path in ${main_conf} (backup: ${backup})"
    else
      rm -f "${tmp}"
    fi
    return 0
  fi

  backup="${main_conf}.plume-backup-$(date +%Y%m%d%H%M%S)"
  cp "${main_conf}" "${backup}"
  {
    printf '\n%s\n' "${begin}"
    printf 'include %s\n' "${plume_conf}"
    printf '%s\n' "${end}"
  } >> "${main_conf}"
  plume_info "native redis: appended plume include to ${main_conf} (backup: ${backup})"
}

plume_native_redis_reload_service() {
  if plume_native_driver_is_mock; then
    plume_info "native redis mock reload"
    return 0
  fi
  local pm
  pm="$(plume_detect_package_manager)"
  case "${pm}" in
    brew)
      local svc
      svc="$(plume_native_driver_brew_service_name redis)" || return 2
      HOMEBREW_NO_AUTO_UPDATE=1 brew services restart "${svc}" >/dev/null 2>&1 \
        || HOMEBREW_NO_AUTO_UPDATE=1 brew services start "${svc}"
      ;;
    apt|dnf)
      local unit os
      unit="$(plume_native_driver_systemd_unit redis)" || return 2
      os="$(plume_detect_os)"
      if [[ "${os}" == "linux" ]] && command -v systemctl >/dev/null 2>&1; then
        systemctl restart "${unit}"
      else
        plume_err "systemd required for native redis reload"
        return 2
      fi
      ;;
    *)
      plume_err "unsupported package manager for redis reload: ${pm}"
      return 2
      ;;
  esac
  plume_info "native redis: service reloaded"
}

plume_native_redis_sync_config() {
  local dry_run="${1:-false}"
  local do_reload="${2:-false}"
  local main_conf plume_conf port password

  if ! plume_native_redis_manage_config_enabled; then
    plume_err "Set PLUME_NATIVE_REDIS_MANAGE_CONFIG=true to apply PLUME_REDIS_* to native redis (see docs/commands/services-redis.md)"
    return 2
  fi

  main_conf="$(plume_native_redis_main_conf_path)"
  plume_conf="$(plume_native_redis_plume_conf_path)"
  port="$(plume_native_redis_effective_port)"
  password="$(plume_native_redis_effective_password)"

  if plume_native_driver_is_mock; then
    if [[ "${dry_run}" == "true" ]]; then
      printf 'action: redis-sync-config\n'
      printf 'plume_conf: %s\n' "${plume_conf}"
      printf 'port: %s\n' "${port}"
      if [[ -n "${password}" ]]; then
        printf 'password_set: true\n'
      else
        printf 'password_set: false\n'
      fi
      printf 'reload: %s\n' "${do_reload}"
      return 0
    fi
    plume_native_redis_write_plume_conf
    if [[ -n "${main_conf}" && -f "${main_conf}" ]]; then
      plume_native_redis_ensure_include
    fi
    [[ "${do_reload}" == "true" ]] && plume_native_redis_reload_service || true
    return 0
  fi

  if [[ -z "${main_conf}" || ! -f "${main_conf}" ]]; then
    plume_err "redis main config not found (install redis, e.g. brew install redis)"
    return 2
  fi

  if [[ "${dry_run}" == "true" ]]; then
    printf 'action: redis-sync-config\n'
    printf 'main_conf: %s\n' "${main_conf}"
    printf 'plume_conf: %s\n' "${plume_conf}"
    printf 'port: %s\n' "${port}"
    printf 'password_set: %s\n' "$( [[ -n "${password}" ]] && printf true || printf false )"
    printf 'reload: %s\n' "${do_reload}"
    return 0
  fi

  plume_native_redis_write_plume_conf
  plume_native_redis_ensure_include

  if [[ "${do_reload}" == "true" ]]; then
    plume_native_redis_reload_service || return 2
  else
    plume_info "restart redis to apply: ./plume.sh services restart redis --mode=native"
  fi
}

plume_native_redis_cli_ping() {
  local port password
  port="$(plume_native_redis_effective_port)"
  password="$(plume_native_redis_effective_password)"
  command -v redis-cli >/dev/null 2>&1 || return 1
  if [[ -n "${password}" ]]; then
    redis-cli -p "${port}" -a "${password}" --no-auth-warning ping 2>/dev/null | grep -q PONG
  else
    redis-cli -p "${port}" ping 2>/dev/null | grep -q PONG
  fi
}
