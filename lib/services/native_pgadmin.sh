#!/usr/bin/env bash
set -euo pipefail

# Native pgAdmin 4 (Laradock pgadmin parity): Python venv under state + HTTP on PGADMIN_PORT.

plume_native_pgadmin_root() {
  printf '%s/native/pgadmin' "$(plume_state_dir)"
}

plume_native_pgadmin_venv() {
  printf '%s/venv' "$(plume_native_pgadmin_root)"
}

plume_native_pgadmin_data_dir() {
  printf '%s/data' "$(plume_native_pgadmin_root)"
}

plume_native_pgadmin_bin() {
  printf '%s/bin/pgadmin4' "$(plume_native_pgadmin_venv)"
}

plume_native_pgadmin_email() {
  printf '%s' "${PGADMIN_DEFAULT_EMAIL:-${PLUME_PGADMIN_DEFAULT_EMAIL:-pgadmin4@pgadmin.org}}"
}

plume_native_pgadmin_password() {
  printf '%s' "${PGADMIN_DEFAULT_PASSWORD:-${PLUME_PGADMIN_DEFAULT_PASSWORD:-admin}}"
}

plume_native_pgadmin_port() {
  printf '%s' "${PGADMIN_PORT:-${PLUME_PGADMIN_PORT:-5050}}"
}

plume_native_pgadmin_ensure_dirs() {
  mkdir -p "$(plume_native_pgadmin_root)" "$(plume_native_pgadmin_data_dir)"
}

plume_native_pgadmin_write_config_local() {
  local pkg_dir config_path port data_dir
  pkg_dir="$1"
  port="$(plume_native_pgadmin_port)"
  data_dir="$(plume_native_pgadmin_data_dir)"
  config_path="${pkg_dir}/config_local.py"
  mkdir -p "${data_dir}"
  cat > "${config_path}" <<EOF
# Generated by Plume — edit PGADMIN_* / PLUME_PGADMIN_* in ~/.config/plume/.env then: services restart pgadmin
import os

DATA_DIR = r'''${data_dir}'''
LOG_FILE = os.path.join(DATA_DIR, 'pgadmin4.log')
SQLITE_PATH = os.path.join(DATA_DIR, 'pgadmin4.db')
SESSION_DB_PATH = os.path.join(DATA_DIR, 'sessions')
STORAGE_DIR = os.path.join(DATA_DIR, 'storage')
DEFAULT_SERVER = '127.0.0.1'
DEFAULT_SERVER_PORT = ${port}
SERVER_MODE = True
MASTER_PASSWORD_REQUIRED = False
EOF
}

# pgadmin4 is a namespace package: __file__ is None; use __path__[0] (D-139).
plume_native_pgadmin_package_dir() {
  local py out
  py="$(plume_native_pgadmin_venv)/bin/python"
  [[ -x "${py}" ]] || return 1
  out="$("${py}" -c 'import pgadmin4; print(pgadmin4.__path__[0])' 2>/dev/null || true)"
  if [[ -n "${out}" && -f "${out}/config.py" ]]; then
    printf '%s\n' "${out}"
    return 0
  fi
  # Fallback: site-packages/pgadmin4 next to venv
  out="$(printf '%s' "$(plume_native_pgadmin_venv)"/lib/python*/site-packages/pgadmin4)"
  # shellcheck disable=SC2086
  for candidate in ${out}; do
    if [[ -f "${candidate}/config.py" ]]; then
      printf '%s\n' "${candidate}"
      return 0
    fi
  done
  return 1
}

plume_native_pgadmin_ensure_mock_runtime() {
  local bin
  plume_native_pgadmin_ensure_dirs
  bin="$(plume_native_pgadmin_bin)"
  mkdir -p "$(dirname "${bin}")"
  cat > "${bin}" <<'EOF'
#!/usr/bin/env bash
# Mock pgadmin4 for hermetic smokes (keep PID alive for health probe)
exec sleep 3600
EOF
  chmod +x "${bin}"
}

plume_native_pgadmin_install() {
  local venv py pip pkg_dir

  plume_native_pgadmin_ensure_dirs

  if declare -F plume_native_driver_is_mock >/dev/null 2>&1 \
    && plume_native_driver_is_mock 2>/dev/null; then
    plume_native_pgadmin_ensure_mock_runtime
    return 0
  fi

  if ! command -v python3 >/dev/null 2>&1; then
    plume_err "python3 required for native pgadmin; install Python 3 or use docker-lite/laradock-bridge"
    return 2
  fi

  venv="$(plume_native_pgadmin_venv)"
  if [[ ! -x "${venv}/bin/python" ]]; then
    plume_info "native pgadmin: creating venv at ${venv}"
    python3 -m venv "${venv}" || return 2
  fi
  py="${venv}/bin/python"
  pip="${venv}/bin/pip"
  if [[ ! -x "$(plume_native_pgadmin_bin)" ]]; then
    plume_info "native pgadmin: pip install pgadmin4"
    "${pip}" install --upgrade pip >/dev/null || return 2
    "${pip}" install "pgadmin4" || return 2
  else
    plume_info "native pgadmin: already installed ($(plume_native_pgadmin_bin))"
  fi

  if ! pkg_dir="$(plume_native_pgadmin_package_dir)"; then
    plume_err "native pgadmin: pgadmin4 package not found after install"
    return 2
  fi
  plume_native_pgadmin_write_config_local "${pkg_dir}"
}

plume_native_pgadmin_sync_config() {
  local dry_run="${1:-false}"
  local pkg_dir

  if [[ "${dry_run}" == "true" ]]; then
    printf 'action: pgadmin-sync-config\n'
    printf 'port: %s\n' "$(plume_native_pgadmin_port)"
    printf 'data_dir: %s\n' "$(plume_native_pgadmin_data_dir)"
    return 0
  fi

  plume_native_pgadmin_ensure_dirs
  if declare -F plume_native_driver_is_mock >/dev/null 2>&1 \
    && plume_native_driver_is_mock 2>/dev/null; then
    plume_native_pgadmin_ensure_mock_runtime
    return 0
  fi

  if ! pkg_dir="$(plume_native_pgadmin_package_dir)"; then
    plume_err "pgadmin not installed; run: services install pgadmin --mode=native"
    return 2
  fi
  plume_native_pgadmin_write_config_local "${pkg_dir}"
}

plume_native_pgadmin_wait_ready() {
  local port="$1"
  local attempts="${2:-30}"
  local i code
  for ((i = 1; i <= attempts; i++)); do
    if command -v curl >/dev/null 2>&1; then
      code="$(curl -s -o /dev/null -w '%{http_code}' --connect-timeout 2 "http://127.0.0.1:${port}/" 2>/dev/null || true)"
      case "${code}" in
        2??|3??) return 0 ;;
      esac
    fi
    sleep 1
  done
  return 1
}

plume_native_pgadmin_start_server() {
  local port pid_file log_file bin

  port="$(plume_native_pgadmin_port)"
  pid_file="$(plume_native_pid_file pgadmin)"
  log_file="$(plume_service_log_file pgadmin native)"
  bin="$(plume_native_pgadmin_bin)"

  plume_native_pgadmin_sync_config "false" || return 2

  if [[ -f "${pid_file}" ]]; then
    local old_pid
    old_pid="$(cat "${pid_file}" 2>/dev/null || true)"
    if [[ -n "${old_pid}" ]] && kill -0 "${old_pid}" 2>/dev/null; then
      plume_info "native pgadmin: already running pid=${old_pid}"
      return 0
    fi
  fi

  if [[ ! -x "${bin}" ]]; then
    plume_err "pgadmin4 binary missing (${bin}); run: services install pgadmin --mode=native"
    return 2
  fi

  mkdir -p "$(dirname "${log_file}")" "$(plume_native_pgadmin_data_dir)"
  # Laradock/docker env names; pip server mode skips interactive setup when set.
  # Detach from parent process group so Cursor/CI shell teardown cannot kill the daemon (D-140).
  PGADMIN_SETUP_EMAIL="$(plume_native_pgadmin_email)" \
    PGADMIN_SETUP_PASSWORD="$(plume_native_pgadmin_password)" \
    PGADMIN_DEFAULT_EMAIL="$(plume_native_pgadmin_email)" \
    PGADMIN_DEFAULT_PASSWORD="$(plume_native_pgadmin_password)" \
    plume_native_detach_daemon "${pid_file}" "${log_file}" "${bin}" \
    || {
      plume_err "native pgadmin: failed to detach daemon"
      return 2
    }
  plume_info "native pgadmin: started on http://127.0.0.1:${port} pid=$(cat "${pid_file}" 2>/dev/null || echo '?')"

  # First boot (setup + flask) can take >3s; wait so status health probe passes.
  if declare -F plume_native_driver_is_mock >/dev/null 2>&1 \
    && plume_native_driver_is_mock 2>/dev/null; then
    return 0
  fi
  if ! plume_native_pgadmin_wait_ready "${port}" 45; then
    plume_warn "native pgadmin: HTTP not ready yet; check ${log_file}"
    if [[ -f "${pid_file}" ]]; then
      local pid
      pid="$(cat "${pid_file}" 2>/dev/null || true)"
      if [[ -n "${pid}" ]] && kill -0 "${pid}" 2>/dev/null; then
        return 0
      fi
    fi
    return 2
  fi
}

plume_native_pgadmin_stop_server() {
  local pid_file pid
  pid_file="$(plume_native_pid_file pgadmin)"
  [[ -f "${pid_file}" ]] || return 0
  pid="$(cat "${pid_file}" 2>/dev/null || true)"
  if [[ -n "${pid}" ]]; then
    kill "${pid}" 2>/dev/null || true
    # Ensure process group cleanup if still alive
    sleep 0.2
    kill -9 "${pid}" 2>/dev/null || true
  fi
  rm -f "${pid_file}"
}
